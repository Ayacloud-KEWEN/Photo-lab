// Regenerates src/api/schema.d.ts from the backend's OpenAPI document.
import { execFileSync } from "node:child_process";
import { existsSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const desktopDir = join(dirname(fileURLToPath(import.meta.url)), "..");
const backendDir = join(desktopDir, "..", "backend");
const venvPython =
  process.platform === "win32"
    ? join(backendDir, ".venv", "Scripts", "python.exe")
    : join(backendDir, ".venv", "bin", "python");
const python = process.env.LUMEN_PYTHON ?? (existsSync(venvPython) ? venvPython : "python");

const spec = execFileSync(python, ["-m", "lumen.openapi"], {
  cwd: backendDir,
  encoding: "utf8",
  env: { ...process.env, LUMEN_LOG_TO_FILE: "false", LUMEN_LOG_LEVEL: "WARNING" },
});
const ast = await openapiTS(JSON.parse(spec));
const header = "// Generated by `npm run gen:api` from the backend OpenAPI schema. Do not edit.\n\n";
const target = join(desktopDir, "src", "api", "schema.d.ts");
writeFileSync(target, header + astToString(ast));
console.log(`Wrote ${target}`);
