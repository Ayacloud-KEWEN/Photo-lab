"""Per-launch bearer token authentication for the local API."""

from __future__ import annotations

import hmac
import logging
import re
import secrets

from starlette.middleware.base import BaseHTTPMiddleware, RequestResponseEndpoint
from starlette.requests import Request
from starlette.responses import JSONResponse, Response
from starlette.types import ASGIApp

logger = logging.getLogger(__name__)

# <img src> cannot send headers, so image endpoints also accept ?token=.
_QUERY_TOKEN_PATHS = re.compile(r"^/api/v1/assets/\d+/thumbnail$")


def generate_token() -> str:
    return secrets.token_urlsafe(32)


class TokenAuthMiddleware(BaseHTTPMiddleware):
    """Rejects every request (except CORS preflight) that lacks the launch token.

    The token is generated by the desktop shell and only shared with its webview,
    so other local processes or web pages cannot drive the backend.
    """

    def __init__(self, app: ASGIApp, token: str) -> None:
        super().__init__(app)
        self._token = token.encode()

    async def dispatch(self, request: Request, call_next: RequestResponseEndpoint) -> Response:
        if request.method == "OPTIONS":
            return await call_next(request)

        header = request.headers.get("authorization", "")
        scheme, _, supplied = header.partition(" ")
        if not header and request.method == "GET" and _QUERY_TOKEN_PATHS.match(request.url.path):
            scheme, supplied = "bearer", request.query_params.get("token", "")
        if scheme.lower() != "bearer" or not hmac.compare_digest(supplied.encode(), self._token):
            logger.warning("rejected unauthenticated request", extra={"path": request.url.path})
            return JSONResponse(
                status_code=401,
                content={"error": {"code": "unauthorized", "message": "Missing or invalid token"}},
            )
        return await call_next(request)
