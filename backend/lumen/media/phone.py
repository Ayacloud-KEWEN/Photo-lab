"""Phones connected by cable (an iPhone, or an Android phone in file-transfer mode).

Windows exposes them through Windows Portable Devices (WPD), not as a drive letter. This
module lists them and reads the photos and videos in their DCIM folder. It only reads:
nothing on the phone is ever written, moved or deleted. No database access here.

``WpdSource`` is the real implementation (``comtypes``); tests use a fake ``PhoneSource``.
A session (``PhoneSource.open``) must be used on the thread that opened it.
"""

from __future__ import annotations

import contextlib
import ctypes
import hashlib
import logging
import sys
import threading
from collections.abc import Generator, Iterator
from dataclasses import dataclass
from datetime import datetime, timedelta
from typing import Any, Literal, Protocol

logger = logging.getLogger(__name__)

DeviceStatus = Literal["ready", "locked"]

# What is copied from DCIM. .AAE (iPhone edit instructions) is left out: LUMEN cannot use it.
PHONE_EXTENSIONS = frozenset(
    {"heic", "heif", "jpg", "jpeg", "png", "dng", "mov", "mp4", "m4v", "hevc"}
)

CHUNK = 1 << 20


class PhoneError(Exception):
    """The phone cannot be read (unplugged, locked, not trusted, no driver)."""


@dataclass(frozen=True)
class PhoneDevice:
    id: str  # stable for a connection (hash of the PnP id): safe in a URL
    name: str
    serial: str  # identifies the phone across connections (what was imported is per phone)
    status: DeviceStatus


@dataclass(frozen=True)
class PhoneFile:
    object_id: str
    key: str  # persistent id on the phone
    name: str  # original file name, e.g. IMG_1234.HEIC
    size: int
    created: datetime | None
    folder: str  # DCIM sub folder on the phone, e.g. 100APPLE


class PhoneSession(Protocol):
    def files(self) -> Iterator[PhoneFile]: ...

    def read(self, file: PhoneFile) -> Generator[bytes]: ...


class PhoneSource(Protocol):
    def devices(self) -> list[PhoneDevice]: ...

    def open(self, device_id: str) -> contextlib.AbstractContextManager[PhoneSession]: ...


def extension(name: str) -> str:
    return name.rsplit(".", 1)[-1].lower() if "." in name else ""


def device_id(pnp_id: str) -> str:
    return hashlib.sha1(pnp_id.encode("utf-8")).hexdigest()[:16]


# --- WPD -------------------------------------------------------------------------------

_OBJ = "{EF6B490D-5CD8-437A-AFFC-DA8B60EE4A3C}"  # WPD_OBJECT_PROPERTIES_V1
_DEV = "{26D4979A-E643-4626-9E2B-736DC0C92FDC}"  # WPD_DEVICE_PROPERTIES_V1
_RES = "{E81E79BE-34F0-41BF-B53F-F1A06AE87842}"  # WPD_RESOURCE_DEFAULT
_FOLDER = "{27E2E392-A111-48E0-AB0C-E17705A05F85}"  # WPD_CONTENT_TYPE_FOLDER
_FUNCTIONAL = "{99ED0160-17FF-4C44-9D98-1D7A6F941921}"  # WPD_CONTENT_TYPE_FUNCTIONAL_OBJECT

_P_NAME = (_OBJ, 4)
_P_PUID = (_OBJ, 5)
_P_CONTENT_TYPE = (_OBJ, 7)
_P_SIZE = (_OBJ, 11)
_P_ORIGINAL_NAME = (_OBJ, 12)
_P_DATE_CREATED = (_OBJ, 18)
_P_DATE_MODIFIED = (_OBJ, 19)
_P_MODEL = (_DEV, 8)
_P_SERIAL = (_DEV, 9)
_P_FRIENDLY = (_DEV, 12)
_RESOURCE_DEFAULT = (_RES, 0)

_VT_DATE = 7
_OLE_EPOCH = datetime(1899, 12, 30)

_lock = threading.Lock()
_libs: tuple[Any, Any] | None = None


def _modules() -> tuple[Any, Any]:
    """The WPD type libraries (generated by comtypes once, then cached)."""
    global _libs
    with _lock:
        if _libs is None:
            if sys.platform != "win32":
                raise PhoneError("Phones can only be read on Windows")
            # Multithreaded apartment: the task runner and the API thread pool use WPD.
            if not hasattr(sys, "coinit_flags"):
                sys.coinit_flags = 0  # type: ignore[attr-defined]
            try:
                import comtypes.client as cc
            except ImportError as exc:  # pragma: no cover - dependency missing
                raise PhoneError("comtypes is not installed") from exc
            _libs = (cc.GetModule("portabledeviceapi.dll"), cc.GetModule("portabledevicetypes.dll"))
        return _libs


_thread = threading.local()


@contextlib.contextmanager
def _com() -> Iterator[None]:
    """COM on this thread, initialized once and **never uninitialized**.

    Uninitializing after each use crashed the backend (an access violation that ends the
    process): when an import stopped midway (cancelled, or the iPhone locked), a file
    stream was still referenced by the exception and was released only after
    ``CoUninitialize``. The task runner and the API threads are long-lived, so keeping COM
    initialized costs nothing."""
    if not getattr(_thread, "com", False):
        import comtypes

        # OSError: already initialized on this thread in another mode, which is fine.
        with contextlib.suppress(OSError):
            comtypes.CoInitializeEx(0)  # type: ignore[no-untyped-call]  # multithreaded
        _thread.com = True
    yield


def _create(coclass: Any, interface: Any) -> Any:
    import comtypes
    import comtypes.client as cc

    return cc.CreateObject(coclass, clsctx=comtypes.CLSCTX_INPROC_SERVER, interface=interface)


class WpdSource:
    """Phones through Windows Portable Devices."""

    def key(self, spec: tuple[str, int]) -> Any:
        import comtypes

        api, _ = _modules()
        key = api._tagpropertykey()
        guid = comtypes.GUID(spec[0])  # type: ignore[no-untyped-call]
        ctypes.memmove(ctypes.byref(key.fmtid), ctypes.byref(guid), 16)
        key.pid = spec[1]
        return key

    def keys(self, specs: list[tuple[str, int]]) -> Any:
        api, types = _modules()
        keys = _create(types.PortableDeviceKeyCollection, api.IPortableDeviceKeyCollection)
        for spec in specs:
            keys.Add(ctypes.byref(self.key(spec)))
        return keys

    def _pnp_ids(self) -> list[str]:
        api, _ = _modules()
        manager = _create(api.PortableDeviceManager, api.IPortableDeviceManager)
        with contextlib.suppress(Exception):
            manager.RefreshDeviceList()
        # The raw method: comtypes' wrapper mishandles these in/out array parameters.
        get_devices = manager._IPortableDeviceManager__com_GetDevices
        count = ctypes.c_ulong(0)
        get_devices(ctypes.POINTER(ctypes.c_wchar_p)(), ctypes.byref(count))
        if not count.value:
            return []
        ids = (ctypes.c_wchar_p * count.value)()
        get_devices(ctypes.cast(ids, ctypes.POINTER(ctypes.c_wchar_p)), ctypes.byref(count))
        return [str(ids[i]) for i in range(count.value) if ids[i]]

    def _open(self, pnp_id: str) -> Any:
        api, types = _modules()
        info = _create(types.PortableDeviceValues, api.IPortableDeviceValues)
        device = _create(api.PortableDevice, api.IPortableDevice)
        try:
            device.Open(pnp_id, info)
        except Exception as exc:
            raise PhoneError(f"The phone cannot be opened: {exc}") from exc
        return device

    def string(self, values: Any, spec: tuple[str, int]) -> str | None:
        try:
            value = values.GetStringValue(ctypes.byref(self.key(spec)))
        except Exception:
            return None
        return str(value) if value else None

    def integer(self, values: Any, spec: tuple[str, int]) -> int | None:
        try:
            return int(values.GetUnsignedLargeIntegerValue(ctypes.byref(self.key(spec))))
        except Exception:
            return None

    def guid(self, values: Any, spec: tuple[str, int]) -> str | None:
        import comtypes

        try:
            raw = values.GetGuidValue(ctypes.byref(self.key(spec)))
        except Exception:
            return None
        guid = comtypes.GUID()  # type: ignore[no-untyped-call]
        ctypes.memmove(ctypes.byref(guid), ctypes.byref(raw), 16)
        return str(guid).upper()

    def date(self, values: Any, spec: tuple[str, int]) -> datetime | None:
        try:
            variant = values.GetValue(ctypes.byref(self.key(spec)))
        except Exception:
            return None
        if variant.vt != _VT_DATE:
            return None
        union = getattr(variant, variant._fields_[-1][0])
        try:
            return _OLE_EPOCH + timedelta(days=float(union.date))
        except (OverflowError, ValueError):
            return None

    def children(self, content: Any, parent: str) -> Iterator[str]:
        try:
            enum = content.EnumObjects(0, parent, None)
        except Exception as exc:
            raise PhoneError(f"Reading the phone failed: {exc}") from exc
        while True:
            try:
                object_id, fetched = enum.Next(1, 0)
            except Exception as exc:
                raise PhoneError(f"Reading the phone failed: {exc}") from exc
            if not fetched or not object_id:
                return
            yield str(object_id)

    def dcim(self, content: Any, props: Any) -> list[str]:
        """Where the photos are: each storage's DCIM folder, or the storage itself when it has
        none (an iPhone shows its month folders, e.g. 202605_a, right in "Internal Storage").
        Empty while an iPhone is locked or does not trust the computer (nothing is listed)."""
        keys = self.keys([_P_NAME, _P_ORIGINAL_NAME, _P_CONTENT_TYPE])
        found = []
        for storage in self.children(content, "DEVICE"):
            if self.guid(props.GetValues(storage, keys), _P_CONTENT_TYPE) != _FUNCTIONAL:
                continue
            children = list(self.children(content, storage))
            dcim = []
            for child in children:
                values = props.GetValues(child, keys)
                name = self.string(values, _P_ORIGINAL_NAME) or self.string(values, _P_NAME) or ""
                if name.upper() == "DCIM":
                    dcim.append(child)
            found.extend(dcim or ([storage] if children else []))
        return found

    def _find(self, wanted: str) -> str:
        for pnp in self._pnp_ids():
            if device_id(pnp) == wanted:
                return pnp
        raise PhoneError("The phone is not connected")

    def devices(self) -> list[PhoneDevice]:
        with _com():
            result = []
            for pnp in self._pnp_ids():
                try:
                    device = self._open(pnp)
                except PhoneError as exc:
                    logger.info("portable device not readable", extra={"reason": str(exc)})
                    continue
                try:
                    content = device.Content()
                    props = content.Properties()
                    values = props.GetValues(
                        "DEVICE", self.keys([_P_FRIENDLY, _P_SERIAL, _P_MODEL])
                    )
                    name = self.string(values, _P_FRIENDLY) or self.string(values, _P_MODEL)
                    serial = self.string(values, _P_SERIAL) or device_id(pnp)
                    status: DeviceStatus = "ready" if self.dcim(content, props) else "locked"
                    result.append(PhoneDevice(device_id(pnp), name or "iPhone", serial, status))
                except Exception as exc:
                    logger.info("portable device skipped", extra={"reason": str(exc)})
                finally:
                    with contextlib.suppress(Exception):
                        device.Close()
            return result

    @contextlib.contextmanager
    def open(self, device_id_: str) -> Iterator[PhoneSession]:
        with _com():
            device = self._open(self._find(device_id_))
            try:
                yield _WpdSession(self, device.Content())
            finally:
                with contextlib.suppress(Exception):
                    device.Close()


class _WpdSession:
    def __init__(self, wpd: WpdSource, content: Any) -> None:
        self._wpd = wpd
        self._content = content
        self._props = content.Properties()
        self._resources = content.Transfer()

    def files(self) -> Iterator[PhoneFile]:
        w, content, props = self._wpd, self._content, self._props
        folders = w.dcim(content, props)
        if not folders:
            raise PhoneError("Unlock the phone and allow this computer to read it")
        keys = w.keys(
            [
                _P_NAME,
                _P_ORIGINAL_NAME,
                _P_PUID,
                _P_CONTENT_TYPE,
                _P_SIZE,
                _P_DATE_CREATED,
                _P_DATE_MODIFIED,
            ]
        )
        stack = [(folder, "") for folder in folders]
        while stack:
            parent, path = stack.pop()
            for object_id in w.children(content, parent):
                try:
                    values = props.GetValues(object_id, keys)
                except Exception as exc:
                    raise PhoneError(f"Reading the phone failed: {exc}") from exc
                name = w.string(values, _P_ORIGINAL_NAME) or w.string(values, _P_NAME) or ""
                if w.guid(values, _P_CONTENT_TYPE) == _FOLDER:
                    stack.append((object_id, f"{path}/{name}" if path else name))
                    continue
                if extension(name) not in PHONE_EXTENSIONS:
                    continue
                yield PhoneFile(
                    object_id=object_id,
                    key=w.string(values, _P_PUID) or f"{path}/{name}",
                    name=name,
                    size=w.integer(values, _P_SIZE) or 0,
                    created=w.date(values, _P_DATE_CREATED) or w.date(values, _P_DATE_MODIFIED),
                    folder=path,
                )

    def read(self, file: PhoneFile) -> Generator[bytes]:
        try:
            _, stream = self._resources.GetStream(
                file.object_id, ctypes.byref(self._wpd.key(_RESOURCE_DEFAULT)), 0, 0
            )
        except Exception as exc:
            raise PhoneError(f"The file cannot be read: {exc}") from exc
        try:
            while True:
                try:
                    buffer, count = stream.RemoteRead(CHUNK)
                except Exception as exc:
                    raise PhoneError(f"Reading the phone failed: {exc}") from exc
                if not count:
                    return
                yield ctypes.string_at(buffer, count)
        finally:
            # Release the stream now (also when the import stops midway), while the
            # device is still open, not whenever the exception's frames are freed.
            del stream
